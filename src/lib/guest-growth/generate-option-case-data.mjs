// Pure generator: no DB/network. A new policy version is required before changing persisted semantics.
import { writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
if (process.versions.unicode !== "17.0")
  throw Error("Generation requires the reviewed Node Unicode17.0 oracle");
const lower = {},
  cased = [],
  ignorable = [];
const add = (ranges, n) => {
  const last = ranges.at(-1);
  if (last && last[1] === n - 1) last[1] = n;
  else ranges.push([n, n]);
};
for (let n = 1; n <= 0x10ffff; n++) {
  if (n >= 0xd800 && n <= 0xdfff) continue;
  const c = String.fromCodePoint(n),
    value = c.toLowerCase();
  if (c !== value) lower[n] = value;
  if (/\p{Cased}/u.test(c)) add(cased, n);
  if (/\p{Case_Ignorable}/u.test(c)) add(ignorable, n);
}
const data = { version: "unicode-17.0-default-lower-v1", lower, cased, ignorable },
  json = JSON.stringify(data),
  sha = createHash("sha256").update(json).digest("hex");
if (sha !== "a1f049c5e3744a4e1ccde3fea423ab85b65704be5ce528bfe46134eac17a135b")
  throw Error("Unicode option policy/data changed; a new reviewed version is required");
if (process.argv.includes("--json")) process.stdout.write(json);
else if (process.argv.includes("--write")) {
  const path = fileURLToPath(new URL("./option-case-data.ts", import.meta.url));
  writeFileSync(
    path,
    `// Generated by generate-option-case-data.mjs using Node Unicode17.0. Authored option text is never rewritten.\nexport const OPTION_CASE_DATA_SHA256 = ${JSON.stringify(sha)};\nconst generated: {readonly version:string;readonly lower:Readonly<Record<string,string>>;readonly cased:readonly(readonly[number,number])[];readonly ignorable:readonly(readonly[number,number])[]} = ${json};\nObject.freeze(generated.lower);for(const ranges of [generated.cased,generated.ignorable]){for(const range of ranges)Object.freeze(range);Object.freeze(ranges);}\nexport const OPTION_CASE_DATA=Object.freeze(generated);\n`,
  );
  console.log(
    JSON.stringify({
      sha,
      mappings: Object.keys(lower).length,
      casedRanges: cased.length,
      ignorableRanges: ignorable.length,
    }),
  );
} else
  console.log(
    JSON.stringify({
      sha,
      mappings: Object.keys(lower).length,
      casedRanges: cased.length,
      ignorableRanges: ignorable.length,
    }),
  );
